"""Model 2 closeout — recover the RAW quantile predictions that post-processing discarded.

This does NOT re-tune, re-specify or re-select anything. The frozen run persisted only the
sorted-and-clipped quantiles, so the raw model outputs have to be regenerated by repeating
the identical fits (same feature table, same fixed hyperparameters, same seed) and are
accepted ONLY if the monotonic set they produce reproduces the frozen artifact. If it does
not, this script says so and refuses to claim the raw values are the originals.

Nothing in the frozen run directory is overwritten; two new files are added beside it.

Usage:
    python src/model2_forecaster/recover_raw_quantiles.py --run outputs/model2_<stamp>
"""
from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path

import numpy as np
import pandas as pd

SRC = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SRC))

from common.io import ML_WORK, write_run_metadata  # noqa: E402
from db import connection_facts, readonly_connection  # noqa: E402
from meters import load_meter_static  # noqa: E402
from model2_forecaster.evaluation import WINDOWS  # noqa: E402
from model2_forecaster.features import build_feature_table  # noqa: E402
from model2_forecaster.run_model2 import (  # noqa: E402
    MODEL_METHOD, _latest_profile, score_window,
)
from model2_forecaster.train import category_levels  # noqa: E402

KEY = ["meter_label", "window", "target_date_saudi"]
NOMINAL_COVERAGE_PCT = 80.0
# pandas' CSV writer drops the last bit of a float64 that needs 17 significant digits
# (210.39999999999415 is written back as 210.39999999999412), so the frozen artifact is not
# a bit-exact record of the doubles that produced it. The refit is therefore compared after
# putting the fresh values through the SAME serialisation round-trip, which isolates the
# model from the file format, and separately against a tolerance far below any reported
# precision.
EXACT_TOL_KWH = 1e-9


def _csv_roundtrip(values: np.ndarray) -> np.ndarray:
    """Push values through pandas' CSV writer and reader, exactly as the frozen run did."""
    buf = io.StringIO()
    pd.DataFrame({"v": values}).to_csv(buf, index=False)
    buf.seek(0)
    return pd.read_csv(buf)["v"].to_numpy()


def _coverage(actual: np.ndarray, low: np.ndarray, high: np.ndarray) -> float:
    return 100.0 * float(((actual >= low) & (actual <= high)).mean())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", type=Path, required=True)
    ap.add_argument("--profile", type=Path, default=None)
    args = ap.parse_args(argv)

    run_dir = args.run if args.run.is_absolute() else ML_WORK / args.run
    frozen_path = run_dir / "forecast_backtest_v2.csv"
    profile_path = args.profile or _latest_profile()
    print(f"frozen run : {run_dir}")
    print(f"profile    : {profile_path}\n")

    profile = pd.read_csv(profile_path, parse_dates=["reading_date_saudi"])
    with readonly_connection() as conn:
        facts = connection_facts(conn)
        static = load_meter_static(conn)
    table = build_feature_table(profile, static)
    categories = category_levels(table)

    frames = []
    for name in WINDOWS:
        print(f"  refitting {name} ...", flush=True)
        frames.append(score_window(table, name, categories))
    fresh = pd.concat(frames, ignore_index=True)

    frozen = pd.read_csv(frozen_path, parse_dates=["issue_date_saudi", "target_date_saudi"])

    f_m = fresh.loc[fresh["method"] == MODEL_METHOD].set_index(KEY).sort_index()
    z_m = frozen.loc[frozen["method"] == MODEL_METHOD].set_index(KEY).sort_index()
    if not f_m.index.equals(z_m.index):
        print("FAIL: the refit does not cover the same rows as the frozen artifact.")
        return 1

    # The frozen artifact stored the sorted-and-clipped values under p10 / prediction / p90.
    pairs = {"p50": ("p50_monotonic", "prediction"),
             "p10": ("p10_monotonic", "p10"),
             "p90": ("p90_monotonic", "p90"),
             "target_kwh": ("target_kwh", "target_kwh")}

    checks, deltas = {"same_rows": True}, {}
    for label, (fresh_col, frozen_col) in pairs.items():
        fresh_vals, frozen_vals = f_m[fresh_col].to_numpy(), z_m[frozen_col].to_numpy()
        deltas[f"max_abs_delta_{label}_kwh"] = float(
            np.abs(fresh_vals - frozen_vals).max())
        checks[f"{label}_identical_after_csv_roundtrip"] = bool(
            np.array_equal(_csv_roundtrip(fresh_vals), frozen_vals))
        checks[f"{label}_within_tolerance"] = bool(
            deltas[f"max_abs_delta_{label}_kwh"] <= EXACT_TOL_KWH)
    checks["crossing_flag_matches"] = bool(np.array_equal(
        f_m["quantile_crossed"].to_numpy().astype(bool),
        z_m["quantile_crossing"].to_numpy().astype(bool)))

    exact = all(checks.values())
    print("\n=== reproduction check against the frozen artifact ===")
    for k, v in checks.items():
        print(f"  {'PASS' if v else 'FAIL'}  {k}")
    print(f"  max absolute deviation before serialisation (tolerance "
          f"{EXACT_TOL_KWH:g} kWh):")
    for k, v in deltas.items():
        print(f"      {k:<34s} {v:.3e}")
    if not exact:
        print("\n  The refit did NOT reproduce the frozen run, so the recovered raw values")
        print("  cannot be claimed to be the originals. Nothing was written.")
        return 1

    model = fresh.loc[fresh["method"] == MODEL_METHOD]

    def diagnostics(group_cols: list[str]) -> pd.DataFrame:
        rows = []
        for keys, g in model.groupby(group_cols, sort=True):
            keys = keys if isinstance(keys, tuple) else (keys,)
            a = g["target_kwh"].to_numpy(float)
            rec = dict(zip(group_cols, keys))
            rec.update({
                "n_observations": len(g),
                "nominal_coverage_pct": NOMINAL_COVERAGE_PCT,
                "coverage_monotonic_pct": _coverage(
                    a, g["p10_monotonic"].to_numpy(float),
                    g["p90_monotonic"].to_numpy(float)),
                "coverage_raw_pct": _coverage(
                    a, g["p10_raw"].to_numpy(float), g["p90_raw"].to_numpy(float)),
                "quantile_crossed_pct": 100 * float(g["quantile_crossed"].mean()),
                "clipped_at_zero_pct": 100 * float(g["clipped_at_zero"].mean()),
                "mean_interval_width_monotonic_kwh": float(
                    (g["p90_monotonic"] - g["p10_monotonic"]).mean()),
                "mean_interval_width_raw_kwh": float(
                    (g["p90_raw"] - g["p10_raw"]).mean()),
            })
            rows.append(rec)
        return pd.DataFrame(rows)

    per_meter = diagnostics(["window", "meter_label"])
    aggregate = diagnostics(["window"])

    cols = ["energy_meter_key", "meter_label", "issue_date_saudi", "target_date_saudi",
            "target_kwh", "window", "method", "prediction",
            "p10_raw", "p50_raw", "p90_raw",
            "p10_monotonic", "p50_monotonic", "p90_monotonic",
            "quantile_crossed", "clipped_at_zero"]
    fresh[cols].to_csv(run_dir / "forecast_backtest_quantiles_v2.csv", index=False)
    per_meter.to_csv(run_dir / "quantile_coverage_raw_vs_monotonic_v2.csv", index=False)

    print("\n=== P10-P90 coverage: raw model output vs monotonic post-processing ===")
    show = ["window", "n_observations", "nominal_coverage_pct", "coverage_monotonic_pct",
            "coverage_raw_pct", "quantile_crossed_pct", "clipped_at_zero_pct",
            "mean_interval_width_monotonic_kwh"]
    print(aggregate[show].to_string(index=False, float_format=lambda v: f"{v:.2f}"))

    write_run_metadata(run_dir, {
        "task": "Model 2 closeout - raw quantile recovery (NO retraining, NO re-selection)",
        "frozen_run": str(run_dir),
        "connection": facts,
        "reproduction_checks": checks,
        "reproduction_max_abs_deviation_kwh": deltas,
        "reproduced_frozen_run": exact,
        "reproduction_note": (
            "The refit is identical to the frozen run after the same CSV serialisation "
            "round-trip, and agrees to within " f"{EXACT_TOL_KWH:g}" " kWh before it. It is "
            "not bit-identical to the numbers READ BACK from the frozen CSV because pandas' "
            "writer drops the last bit of a float64 needing 17 significant digits; that is "
            "a property of the stored file, not of the model."),
        "method": (
            "The frozen run persisted only the sorted-and-clipped quantiles, so the raw "
            "model outputs were regenerated by repeating the identical fits (same feature "
            "table, same fixed hyperparameters, same seed). They are accepted only because "
            "the monotonic set they produce is bit-identical to the frozen artifact, which "
            "establishes that the recovered raw values are the originals and not a new "
            "model's. No hyperparameter, feature, window or threshold was changed."),
        "column_semantics": {
            "p10_raw/p50_raw/p90_raw": (
                "exactly what each independently fitted quantile model predicted; "
                "never overwritten"),
            "p10_monotonic/p50_monotonic/p90_monotonic": (
                "the raw triple sorted ascending, then clipped at zero"),
            "quantile_crossed": "the RAW triple was out of order for this row",
            "clipped_at_zero": "clipping changed at least one value for this row",
            "prediction": "p50_monotonic - the value every reported WAPE and MAE uses",
        },
        "coverage_basis": (
            "Every P10-P90 coverage figure reported for Model 2, including the 71-72% "
            "headline, is computed from the MONOTONIC set (p10_monotonic, p90_monotonic). "
            "Raw-set coverage is reported beside it for comparison only."),
        "coverage_aggregate": aggregate.to_dict("records"),
        "artifacts_added": ["forecast_backtest_quantiles_v2.csv",
                            "quantile_coverage_raw_vs_monotonic_v2.csv"],
        "artifacts_overwritten": [],
    }, filename="run_metadata_quantile_recovery.json")

    print(f"\nartifacts added to {run_dir} (nothing overwritten)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
